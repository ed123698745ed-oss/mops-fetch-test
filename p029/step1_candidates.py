# 029 步驟1：從 MOPS 每日重大訊息公告總表抽出「處分資產」候選並以固定規則分類
import pandas as pd, glob, re, sys
REPO = sys.argv[1]
df = pd.concat([pd.read_csv(f, dtype=str) for f in sorted(glob.glob(f"{REPO}/merged/MOPS每日重大訊息_公告總表_20*.csv.gz"))], ignore_index=True)
import os
FROM, TO = os.environ.get("P029_FROM", "20100101"), os.environ.get("P029_TO", "99999999")   # R03：2007～2009 獨立驗證另跑
df = df[(df["發言日期"] >= FROM) & (df["發言日期"] <= TO)].copy()
df["主旨"] = df["主旨"].fillna("").str.replace("\n", "", regex=False)
df["說明"] = df["說明"].fillna("")
df = df.drop_duplicates(["公司代號", "發言日期", "發言時間", "主旨"])
DISP = r"處分|出售|標售|讓售|售予|賣出|轉讓"
c = df[df["主旨"].str.contains(DISP)].copy()
# 標的欄位（第1項）
def item1(s):
    m = re.search(r"^1\.\s*(?:標的物之名稱及性質|證券名稱|標的物名稱)[^:：\n]*[:：]?\s*\n?(.*?)(?=\n\s*2\.)", s, re.S)
    return re.sub(r"\s+", "", m.group(1))[:200] if m else ""
c["標的"] = c["說明"].apply(item1)
c["主旨標的"] = c["主旨"] + "｜" + c["標的"]
EXC = [
 ("內部人持股轉讓（非公司資產處分）", r"董事.{0,10}(轉讓|持股)|當然解任|申報轉讓|內部人|大股東|監察人.{0,6}轉讓|經理人.{0,6}轉讓"),
 ("非處分：買回／員工認股／放棄增資", r"買回|員工|認股|放棄.{0,10}增資|現金增資|私募.{0,6}(發行|普通股)"),
 ("非處分：掛牌申請", r"新三板|掛牌|上市申請|上櫃申請"),
 ("買進資產：參與標售／得標", r"簽訂.{0,20}標售|取得.{0,40}標售|參與.{0,20}標售|得標|標購|承購"),
 ("非資產處分（裁罰／假處分／訴訟）", r"罰鍰|裁罰|假處分|定暫時狀態|行政處分|處分案|糾正|警告|懲處|處分書|處分之說明|核處|停止處分"),
 ("制度／程序修訂", r"處理程序|作業程序|處理準則|辦法|章程"),
 ("關係人月報／彙總", r"關係人.*(進貨|銷貨|應收|應付)|月份.*取得.*處分|月份.*處分"),
 ("會計重分類", r"重分類|備供出售"),
 ("庫藏股", r"庫藏股"),
 ("使用權資產（Ed 10/22 排除）", r"使用權"),
 ("例行金融交易：債權", r"債權|不良|應收帳款|授信|聯貸|放款"),
 ("例行金融交易：金融商品", r"基金|債券|公司債|票券|定存|存款|理財|附買回|附賣回|金融債|ETF|指數股票型|結構型|組合式|貨幣市場|短期票|商業本票|保本|連結|衍生|期貨|選擇權|外匯|利率交換|國庫券|政府公債|資產證券化|受益證券|受益憑證|REITs?|不動產投資信託|[^A-Za-z]R\d\b|R\d\)"),
 ("營建存貨例行銷售", r"承攬合約|工程合約|建案|預售|餘屋|推案|銷售.*(房屋|住宅)|個案"),
 ("媒體澄清／傳聞", r"澄清|媒體|報導|報載|傳聞|說明.*新聞"),
 ("僅構想無具體決定", r"評估|考慮|研議|洽談|意向書|備忘錄|MOU|可能出售|規劃出售"),
 ("買進資產為主", r"^(?!.*(處分|出售|標售|讓售|售予|賣出|轉讓)).*取得"),
]
def why(s):
    for name, pat in EXC:
        if re.search(pat, s, re.I): return name
    return ""
c["排除原因"] = c["主旨標的"].apply(why)
# 「處分有價證券」等泛稱：依標的判斷股權，否則列待核
def cat(s):
    if re.search(r"(處分|出售|讓售).{0,20}(機器|設備|模具|生產線)", s) and not re.search(r"土地|不動產|廠房|房地|建物", s): return "其他資產"
    if re.search(r"作價入股.{0,20}股權|(處分|出售|讓售|轉讓).{0,30}股權", s) and not re.search(r"(處分|出售).{0,10}(土地|不動產|廠房|房地)", s): return "股權投資"
    if re.search(r"土地|房地|不動產|廠房|建物|房屋|大樓|廠辦|辦公室|地號|段\d|廠區|宿舍|地上物|農地|樓層|透天|店面|商辦", s): return "不動產"
    if re.search(r"股權|股份|股票|普通股|特別股|出資額|持股|出資|權益|子公司.*%|股\)", s): return "股權投資"
    if re.search(r"機器|設備|模具|生產線|專利|商標|無形資產|營業讓與|事業部|業務讓與|部門|營業權|礦權|船舶|飛機|航空器|車輛", s): return "其他資產"
    return "待核（類型不明）"
c["資產類型"] = c["主旨標的"].apply(cat)
c.loc[(c["排除原因"] == "") & c["主旨"].str.contains("有價證券") & (c["資產類型"] == "待核（類型不明）"), "排除原因"] = "待核：有價證券泛稱、標的不明"
c.loc[(c["排除原因"] == "") & (c["資產類型"] == "待核（類型不明）"), "排除原因"] = "待核：資產類型不明"
c.to_pickle("c1.pkl")
print(len(df), "全部公告；含處分字詞", len(c))
print(c["排除原因"].value_counts().to_string())
print(c[c["排除原因"] == ""]["資產類型"].value_counts().to_string())
